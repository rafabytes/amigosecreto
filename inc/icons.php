/**
 * Botão "mostrar senha" para colocar depois de um <input type="password"> dentro de um
 * <div class="relative">. O comportamento fica em src/js/app.js ([data-password-toggle]).
 * O componente React equivalente é PasswordInput (src/js/components/ui.jsx).
 */
function as_password_toggle() {
	return sprintf(
		'<button type="button" class="password-toggle group" data-password-toggle aria-pressed="false" aria-label="%s" title="%s">%s%s</button>',
		esc_attr__( 'Mostrar senha', 'amigosecreto' ),
		esc_attr__( 'Mostrar senha', 'amigosecreto' ),
		as_icon( 'eye', 'size-5 group-aria-pressed:hidden' ),
		as_icon( 'eye-off', 'size-5 hidden group-aria-pressed:block' )
	);
}

function as_icon( $name, $class = 'size-5' ) {
	$paths = as_icon_paths();
	if ( ! isset( $paths[ $name ] ) ) {
		return '';
	}
	return sprintf(
		'<svg class="%s" xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" stroke-width="1.75" stroke="currentColor" aria-hidden="true"><path stroke-linecap="round" stroke-linejoin="round" d="%s"/></svg>',
		esc_attr( $class ),
		esc_attr( $paths[ $name ] )
	);
}
